-- Reporting views over the mirrored verdicts and the archive (SNOWFLAKE-PORT-SPEC.md §3). Same `closes` rule as
-- mig.v_reconciliation_tables on PostgreSQL, which stays the authoritative source for report-service.
CREATE OR REPLACE VIEW MIG.V_RUN_SUMMARY AS
SELECT
    l.RUN_ID,
    l.NAMESPACE,
    l.TABLE_NAME,
    l.TABLE_ORDER,
    l.TABLE_ROLE,
    COALESCE(l.EXTRACTED, 0)                                    AS EXTRACTED,
    COALESCE(l.LOADED, 0)                                       AS LOADED,
    COALESCE(l.VALIDATED, 0)                                    AS VALIDATED,
    COALESCE(l.PURGED, 0)                                       AS PURGED,
    COALESCE(l.REJECTED, 0) + COALESCE(l.VALIDATE_FAILED, 0)    AS FAILED,
    COALESCE(l.REJECTED, 0)                                     AS REJECTED,
    COALESCE(l.VALIDATE_FAILED, 0)                              AS VALIDATE_FAILED,
    COALESCE(l.PURGE_INTENDED, 0)                               AS PURGE_INTENDED,
    l.PURGE_DRY_RUN,
    r.STATUS                                                    AS RUN_STATUS,
    CASE
        WHEN COALESCE(l.EXTRACTED, -1) <> COALESCE(l.LOADED, 0) + COALESCE(l.REJECTED, 0) THEN FALSE
        WHEN COALESCE(l.LOADED, -1) <> COALESCE(l.VALIDATED, 0) + COALESCE(l.VALIDATE_FAILED, 0) THEN FALSE
        WHEN l.TABLE_ROLE = 'reference' AND COALESCE(l.PURGED, 0) <> 0 THEN FALSE
        WHEN l.TABLE_ROLE = 'data' AND r.PURGE_ENABLED AND COALESCE(l.PURGED, -1) <> COALESCE(l.VALIDATED, 0) THEN FALSE
        WHEN l.TABLE_ROLE = 'data' AND NOT r.PURGE_ENABLED
             AND (COALESCE(l.PURGE_INTENDED, -1) <> COALESCE(l.VALIDATED, 0) OR COALESCE(l.PURGED, 0) <> 0) THEN FALSE
        ELSE TRUE
    END                                                         AS CLOSES
FROM MIG.RUN_LEDGER l
JOIN MIG.RUNS r ON r.RUN_ID = l.RUN_ID AND r.NAMESPACE = l.NAMESPACE;

CREATE OR REPLACE VIEW MIG.V_FAILURES AS
SELECT RUN_ID, NAMESPACE, TABLE_NAME, SOURCE_KEY, RULE_NAME, TARGET_HASH IS NULL AS MISSING_ON_TARGET, VALIDATED_AT
FROM MIG.VALIDATION
WHERE STATUS = 'FAILED';

-- Archive row counts per namespace and run: the "target has the rows" proof, independent of the report UI.
CREATE OR REPLACE VIEW MIG.V_ARCHIVE_COUNTS AS
SELECT 'RETNPLCY' AS TABLE_NAME, NAMESPACE, MIGRATED_RUN_ID, COUNT(*) AS ROWS_ARCHIVED FROM ARCH.RETNPLCY
GROUP BY NAMESPACE, MIGRATED_RUN_ID
UNION ALL
SELECT 'DOCARCH', NAMESPACE, MIGRATED_RUN_ID, COUNT(*) FROM ARCH.DOCARCH GROUP BY NAMESPACE, MIGRATED_RUN_ID
UNION ALL
SELECT 'FILEAUD', NAMESPACE, MIGRATED_RUN_ID, COUNT(*) FROM ARCH.FILEAUD GROUP BY NAMESPACE, MIGRATED_RUN_ID;

-- Retention-class totals on the archive (MIG-07 evidence read directly from Snowflake).
CREATE OR REPLACE VIEW MIG.V_CLASS_TOTALS AS
SELECT NAMESPACE, MIGRATED_RUN_ID, RTRIM(RETENTION_CLASS) AS RETENTION_CLASS, COUNT(*) AS ROW_COUNT,
       SUM(STORAGE_CHARGE) AS CHARGE_SUM
FROM ARCH.DOCARCH
GROUP BY NAMESPACE, MIGRATED_RUN_ID, RTRIM(RETENTION_CLASS);
